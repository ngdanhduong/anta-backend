CREATE TABLE IF NOT EXISTS app_users (
    id VARCHAR(64) PRIMARY KEY,
    identifier VARCHAR(255) NOT NULL UNIQUE,
    identifier_norm VARCHAR(255) NOT NULL UNIQUE,
    display_name VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    password_login BOOLEAN NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at_ms BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id VARCHAR(64) NOT NULL,
    role VARCHAR(64) NOT NULL,
    branch_id VARCHAR(64) NOT NULL DEFAULT '',
    PRIMARY KEY (user_id, role, branch_id)
);

CREATE TABLE IF NOT EXISTS user_favorites (
    user_id VARCHAR(64) NOT NULL,
    branch_id VARCHAR(64) NOT NULL,
    sort_order BIGINT NOT NULL,
    PRIMARY KEY (user_id, branch_id)
);

CREATE TABLE IF NOT EXISTS revoked_tokens (
    token_hash VARCHAR(128) PRIMARY KEY,
    revoked_at_ms BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS otp_challenges (
    challenge_id VARCHAR(64) PRIMARY KEY,
    identifier VARCHAR(255) NOT NULL,
    code VARCHAR(16) NOT NULL,
    expires_at_ms BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS verification_tokens (
    token VARCHAR(128) PRIMARY KEY,
    identifier VARCHAR(255) NOT NULL,
    expires_at_ms BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS booking_holds (
    hold_id VARCHAR(64) PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL,
    yard_id VARCHAR(64) NOT NULL,
    branch_id VARCHAR(64) NOT NULL,
    starts_at_ms BIGINT NOT NULL,
    ends_at_ms BIGINT NOT NULL,
    total BIGINT NOT NULL,
    expires_at_ms BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS bookings (
    id VARCHAR(64) PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL,
    branch_id VARCHAR(64) NOT NULL,
    yard_id VARCHAR(64) NOT NULL,
    branch_name VARCHAR(255) NOT NULL,
    branch_address TEXT NOT NULL,
    branch_image TEXT,
    yard_name VARCHAR(255) NOT NULL,
    sport_name VARCHAR(128) NOT NULL,
    branch_timezone VARCHAR(64) NOT NULL,
    starts_at_ms BIGINT NOT NULL,
    ends_at_ms BIGINT NOT NULL,
    hourly_price BIGINT NOT NULL,
    amount BIGINT NOT NULL,
    status VARCHAR(64) NOT NULL,
    source VARCHAR(32) NOT NULL,
    created_at_ms BIGINT NOT NULL,
    payment_expires_at_ms BIGINT,
    confirm_deadline_at_ms BIGINT
);

CREATE TABLE IF NOT EXISTS booking_status_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id VARCHAR(64) NOT NULL,
    created_at_ms BIGINT NOT NULL,
    from_status VARCHAR(64),
    to_status VARCHAR(64) NOT NULL,
    reason TEXT
);

CREATE TABLE IF NOT EXISTS payment_intents (
    id VARCHAR(64) PRIMARY KEY,
    booking_id VARCHAR(64) NOT NULL,
    user_id VARCHAR(64) NOT NULL,
    amount BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    refund_status VARCHAR(32),
    updated_at_ms BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS court_blocks (
    id VARCHAR(64) PRIMARY KEY,
    branch_id VARCHAR(64) NOT NULL,
    yard_id VARCHAR(64) NOT NULL,
    starts_at_ms BIGINT NOT NULL,
    ends_at_ms BIGINT NOT NULL,
    reason TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS refunds (
    id VARCHAR(64) PRIMARY KEY,
    order_code VARCHAR(64) NOT NULL,
    provider VARCHAR(32) NOT NULL,
    amount BIGINT NOT NULL,
    percent INT NOT NULL,
    reason TEXT NOT NULL,
    status VARCHAR(32) NOT NULL,
    provider_ref VARCHAR(128),
    created_at_ms BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at_ms BIGINT NOT NULL,
    actor_id VARCHAR(64) NOT NULL,
    action VARCHAR(128) NOT NULL,
    target_type VARCHAR(64) NOT NULL,
    target_id VARCHAR(128) NOT NULL,
    details_json TEXT NOT NULL
);
